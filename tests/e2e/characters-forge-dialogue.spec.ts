import { expect, test } from '@playwright/test'

test('personagens coerentes, diálogo com retrato e respostas, mercado, forja e arma em combate', async ({ page }) => {
  test.setTimeout(100_000)
  page.setDefaultTimeout(15_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/login')
  await page.getByRole('button', { name: 'Continuar como convidado local' }).click()
  await page.getByPlaceholder('Ex.: Aron').fill('Aron')
  await page.getByRole('button', { name: 'Confirmar Terrírian' }).click()
  await page.getByRole('button', { name: 'Aumentar Força', exact: true }).click()
  await page.getByRole('button', { name: 'Escolher Espada Longa', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Vincular Espada Longa — Grau I', exact: true }).click()
  await page.evaluate(async () => {
    const { useGameStore } = await import('/src/state/gameStore.ts')
    const store = () => useGameStore.getState()
    store().recordCutsceneViewed('terran_arrival')
    store().recordCutsceneViewed('astravel_call')
    // Four valid clan offers exercise removal of the old three-quest cap.
    store().travelInTerran('location_terran_clan_hall')
    for (const [clan, quest] of [['dunavar','clan_dunavar_01'], ['rustal','clan_rustal_01'], ['cebios_esti','clan_cebios_01'], ['estres_do_et','clan_estres_01']]) {
      store().discoverClan(clan); store().offerQuest(quest); store().acceptQuest(quest)
    }
    store().travelInTerran('location_terran_portal_plaza')
    const save = structuredClone(store().save!)
    save.wallet.gold = 1000
    for (const [i, [definitionId, quantity]] of ([['drop_blackroot_core',2], ['drop_mycelial_fiber',4], ['drop_fungal_gel',1]] as const).entries()) {
      save.inventory.push({ instanceId: `e2e-resource-${i}`, definitionId, quantity, rarity: 'uncommon', locked: false, favorite: false, acquiredAt: save.updatedAt })
    }
    useGameStore.setState({ save })
  })
  const rosetta = page.getByRole('button', { name: 'Conversar com Rosetta', exact: true })
  await expect(rosetta.locator('.npc-question-bubble')).toHaveText('?')
  await expect(rosetta.locator('.npc-question-bubble')).toHaveCSS('background-color','rgb(172, 48, 61)')
  await rosetta.click()
  const guide = page.getByRole('dialog', { name: 'Orientações de Rosetta' })
  await expect(guide).toBeVisible()
  await expect(guide.locator('.vn-cast__npc img')).toHaveAttribute('src', /npc_rosetta_portrait/)
  await expect(guide.locator('.vn-cast__player .equipped-character__body')).toHaveAttribute('src', /player_default/)
  await expect(guide.getByText(/4 missões em andamento · sem limite/)).toBeVisible()
  await page.screenshot({ path: '/tmp/terrunia-dialogue-cast.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(guide).toBeVisible()
  const mobile = await guide.boundingBox()
  expect(mobile).not.toBeNull()
  expect(mobile!.x).toBeGreaterThanOrEqual(0)
  expect(mobile!.x + mobile!.width).toBeLessThanOrEqual(390)
  expect(mobile!.y).toBeGreaterThanOrEqual(0)
  expect(mobile!.y + mobile!.height).toBeLessThanOrEqual(844)
  await expect(guide.getByRole('button', { name: 'Encerrar diálogo', exact: true })).toBeInViewport()
  await page.screenshot({ path: '/tmp/terrunia-dialogue-mobile.png' })
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Ir para Mercado', exact: true }).click()
  await expect(page.getByRole('img', { name: /Interior pixelado de Mercado/ })).toBeVisible({ timeout: 20_000 })
  await page.getByRole('button', { name: 'Falar com Neris dentro do local', exact: true }).click()
  const shop = page.getByRole('dialog', { name: 'Neris', exact: true })
  await expect(shop).toBeVisible()
  const buy = shop.getByRole('button', { name: 'Comprar Lasca da Ruína por 60 ouro', exact: true })
  await buy.click(); await buy.click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Sair do interior para as ruas de Terran', exact: true }).click()
  await page.getByRole('button', { name: 'Ir para Casa do Ferreiro', exact: true }).click()
  await expect(page.getByRole('img', { name: /Interior pixelado de Casa do Ferreiro/ })).toBeVisible({ timeout: 20_000 })
  await page.getByRole('button', { name: 'Falar com Durnan dentro do local', exact: true }).click()
  const forge = page.getByRole('dialog', { name: 'Durnan · Casa do Ferreiro', exact: true })
  await expect(forge).toBeVisible()
  for (const name of ['Liga Rúnica','Núcleo de Arma','Aplicar Têmpera à Arma','Resina Micelial Tratada','Aplicar Acabamento Micelial']) {
    await forge.getByRole('button', { name: `Forjar: ${name}`, exact: true }).click()
  }
  await expect(forge.getByRole('button', { name: 'Forjar: Aplicar Têmpera à Arma', exact: true })).toBeDisabled()
  await page.screenshot({ path: '/tmp/terrunia-forge-dialogue.png' })
  await page.keyboard.press('Escape')
  await page.reload()
  await page.getByRole('button', { name: 'Continuar com Aron', exact: true }).click()
  const persisted = await page.evaluate(async () => {
    const { useGameStore } = await import('/src/state/gameStore.ts')
    const save = useGameStore.getState().save!
    return { active: Object.values(save.quests).filter((quest) => quest.status === 'active').length,
      forging: save.boundItems[save.character.bondedEquipment.weapon!].forging?.upgradeIds, gold: save.wallet.gold }
  })
  expect(persisted.active).toBe(4)
  expect(persisted.forging).toEqual(['forge_tempered_weapon','forge_mycelial_finish'])
  expect(persisted.gold).toBe(720)
  await page.evaluate(async () => {
    const { useGameStore } = await import('/src/state/gameStore.ts')
    const store = () => useGameStore.getState()
    store().travelInTerran('location_terran_eldamar_house'); store().discoverEldamar()
    store().offerQuest('vs_astravel_first_contact'); store().acceptQuest('vs_astravel_first_contact')
    store().travelInTerran('location_terran_portal_plaza'); store().enterAstravel()
  })
  await page.getByRole('button', { name: 'Seguir objetivo' }).click()
  await expect(page.getByRole('heading', { name: 'Primeira Presença Fungorra', exact: true })).toBeVisible({ timeout: 20_000 })
  const actor = page.locator('.pixel-battle__hero .equipped-character')
  await expect(actor).toHaveAttribute('data-facing', 'right')
  await expect(actor).toHaveAttribute('data-weapon-id', 'bound_weapon_long_sword')
  await expect(actor.locator('.equipped-character__weapon')).toHaveAttribute('src', /weapon_long_sword/)
  await expect(page.locator('.world-scene-transition')).toHaveCount(0)
  await page.screenshot({ path: '/tmp/terrunia-armed-player.png' })
  expect(errors).toEqual([])
})
