import { expect, test } from '@playwright/test'

test('conversas interativas, aceite cinza, diário em linhas e mochila antes dos Vínculos', async ({ page }) => {
  test.setTimeout(120_000)
  page.setDefaultTimeout(20_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/login')
  await page.getByRole('button', { name: 'Continuar como convidado local' }).click()
  await page.getByPlaceholder('Ex.: Aron').fill('Aron')
  await page.getByRole('button', { name: 'Confirmar Terrírian' }).click()
  await page.getByRole('button', { name: 'Aumentar Força', exact: true }).click()
  await page.getByRole('button', { name: 'Escolher Espada Longa', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Vincular Espada Longa — Grau I', exact: true }).click()
  const arlenGreeting = await page.evaluate(async () => {
    const { useGameStore } = await import('/src/state/gameStore.ts')
    const { content } = await import('/src/content/catalog.ts')
    const { refreshQuestAvailability } = await import('/src/domain/quests/questEngine.ts')
    const store = () => useGameStore.getState()
    store().recordCutsceneViewed('terran_arrival'); store().recordCutsceneViewed('astravel_call')
    let save = structuredClone(store().save!)
    // Story gates and extra journal entries are fixtures. Conversation, acceptance,
    // navigation, filtering and inventory ordering are exercised through the UI.
    for (const id of ['vs_astravel_first_contact','main_terran_first_home','main_vorren_bestiary']) save.quests[id].status = 'completed'
    for (const id of ['main_astravel_lost_hunters','side_street_liora','delivery_neris_stock']) save.quests[id].status = 'active'
    save.settings.reducedMotion = true
    save.world.currentLocationId = 'location_terran_portal_plaza'
    save.inventory.push({ instanceId: 'ui-sample', definitionId: 'drop_ruin_shard', quantity: 1, rarity: 'rare', locked: false, favorite: false, acquiredAt: save.updatedAt })
    save = refreshQuestAvailability(save, content, save.updatedAt)
    useGameStore.setState({ save })
    return content.npcs.npc_street_arlen.dialogue[0]
  })
  await page.getByRole('combobox', { name: 'Destino em Terran' }).selectOption('npc:presence_street_arlen')
  const arlen = page.getByRole('dialog', { name: 'Arlen', exact: true })
  await expect(arlen).toBeVisible({ timeout: 20_000 })
  await expect(arlen.getByRole('heading', { name: 'Arlen', exact: true })).toHaveCount(1)
  await expect(arlen.locator('.vn-cast__npc img')).toHaveCount(1)
  await expect(arlen.locator('.terran-quest-dialog__npc')).toHaveCount(0)
  await arlen.getByRole('button', { name: 'Vamos falar de outra coisa.', exact: true }).click()
  await expect(arlen.getByText(arlenGreeting, { exact: true })).toHaveCount(1)
  await arlen.getByRole('button', { name: 'Como estão as rotas de entrega?', exact: true }).click()
  await expect(arlen.locator('.vn-speech')).toContainText('Tenho destinatários esperando')
  await expect(arlen.locator('.vn-speech')).toBeFocused()
  await arlen.getByRole('button', { name: 'O que tem acontecido por aqui?', exact: true }).click()
  await expect(arlen.locator('.vn-speech')).toContainText('Gosto deste trecho perto de Eldamar')
  await arlen.getByRole('button', { name: 'Tem algum conselho para mim?', exact: true }).click()
  await expect(arlen.locator('.vn-speech')).toContainText('confira a mochila antes de voltar')
  await arlen.getByRole('button', { name: 'Sobre a missão: Caminhos de Entrega', exact: true }).click()
  await arlen.getByRole('button', { name: 'Como posso avançar?', exact: true }).click()
  await expect(arlen.locator('.vn-speech')).toContainText('Fungorro Rastejante')
  await arlen.getByRole('button', { name: 'Entendi. Vamos retomar o trabalho.', exact: true }).click()
  await arlen.getByRole('button', { name: 'O que recebo ao concluir?', exact: true }).click()
  await expect(arlen.locator('.vn-speech')).toContainText('18 Ouro')
  await arlen.getByRole('button', { name: 'Ouvir a oferta', exact: true }).click()
  await arlen.getByRole('button', { name: 'Aceitar missão', exact: true }).click()
  const marker = page.locator('[aria-label="Conversar com Arlen"] .npc-quest-marker')
  await expect(marker).toHaveAttribute('data-quest-state', 'active')
  await expect(marker).toHaveCSS('color', 'rgb(157, 162, 165)')
  await expect(page.locator('.notification--neutral')).toContainText('Missão aceita')
  await page.getByRole('button', { name: 'Conversar com Arlen', exact: true }).click()
  await expect(arlen.locator('.vn-speech')).toContainText('Conto com você para o trabalho que combinamos.')
  await page.screenshot({ path: '/tmp/terrunia-dialogue-interaction.png' })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Ir para Posto de Vorren', exact: true }).click()
  await expect(page.getByRole('img', { name: /Interior pixelado de Posto de Vorren/ })).toBeVisible({ timeout: 20_000 })
  await page.getByRole('button', { name: 'Falar com Vorren dentro do local', exact: true }).click()
  const vorren = page.getByRole('dialog', { name: 'Vorren', exact: true })
  await expect(vorren).toBeVisible()
  const main = await vorren.locator('.npc-quest-group--main').boundingBox()
  const secondary = await vorren.locator('.npc-quest-group--secondary').boundingBox()
  expect(main!.y + main!.height).toBeLessThanOrEqual(secondary!.y)
  const missionRows = await vorren.locator('.npc-quest-choices button').all()
  for (let index = 1; index < missionRows.length; index++) {
    const before = await missionRows[index - 1].boundingBox(), after = await missionRows[index].boundingBox()
    expect(after!.y).toBeGreaterThanOrEqual(before!.y + before!.height)
    expect(Math.abs(after!.width - before!.width)).toBeLessThan(2)
  }
  await page.screenshot({ path: '/tmp/terrunia-npc-quest-rows.png' })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Sair do interior para as ruas de Terran', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir Missões', exact: true }).click()
  const journal = page.getByRole('region', { name: 'Diário de missões', exact: true })
  const storyBounds = await journal.locator('.quest-journal-group--main').boundingBox()
  const sideBounds = await journal.locator('.quest-journal-group--secondary').boundingBox()
  expect(storyBounds!.y + storyBounds!.height).toBeLessThan(sideBounds!.y)
  const rows = await journal.locator('.quest-tile').all()
  for (let index = 1; index < rows.length; index++) {
    const before = await rows[index - 1].boundingBox(), after = await rows[index].boundingBox()
    expect(after!.y).toBeGreaterThan(before!.y)
    expect(Math.abs(before!.width - after!.width)).toBeLessThan(2)
  }
  await page.screenshot({ path: '/tmp/terrunia-journal-rows.png' })
  await journal.getByRole('button', { name: 'Detalhes da missão Caçadores Perdidos', exact: true }).click()
  await expect(journal.getByRole('region', { name: 'Detalhes: Caçadores Perdidos', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Fechar painel', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir Inventário', exact: true }).click()
  const inventory = page.getByRole('complementary', { name: 'Painel lateral: Inventário', exact: true })
  await expect(inventory.locator('.arcane-panel').first().getByRole('heading', { name: 'Mochila', exact: true })).toBeVisible()
  await expect(inventory.getByRole('heading', { name: 'Status do personagem', exact: true })).toHaveCount(0)
  await expect(page.getByRole('complementary', { name: 'Status permanente do personagem', exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/terrunia-backpack-first.png' })
  await page.getByRole('link', { name: 'Abrir Menu', exact: true }).click()
  await page.getByRole('link', { name: 'Nexo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Nexo do personagem', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Status do personagem', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Terran', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('combobox', { name: 'Destino em Terran' }).selectOption('npc:presence_street_arlen')
  await expect(arlen).toBeVisible({ timeout: 20_000 })
  await arlen.getByRole('button', { name: 'Vamos falar de outra coisa.', exact: true }).click()
  await arlen.getByRole('button', { name: 'Como estão as rotas de entrega?', exact: true }).click()
  const bounds = await arlen.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(844)
  await expect(arlen.getByRole('button', { name: 'Encerrar diálogo', exact: true })).toBeInViewport()
  await page.screenshot({ path: '/tmp/terrunia-dialogue-compact-mobile.png' })
  await page.keyboard.press('Escape')
  await page.evaluate(async () => {
    const { useGameStore } = await import('/src/state/gameStore.ts')
    const { content } = await import('/src/content/catalog.ts')
    const { applyQuestEvent } = await import('/src/domain/quests/questEngine.ts')
    const save = useGameStore.getState().save!
    useGameStore.setState({ save: applyQuestEvent(save, { type: 'kill', targetId: 'enemy_fungorro_crawler', amount: 2 }, content, save.updatedAt) })
  })
  await expect(marker).toHaveAttribute('data-quest-state', 'turn-in')
  await expect(marker).toHaveCSS('color', 'rgb(120, 215, 240)')
  expect(errors).toEqual([])
})
