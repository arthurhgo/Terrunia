import { expect, test } from '@playwright/test'

test('v0.6: modo isométrico integrado conserva HUD, navegação, interiores e retorno clássico', async ({ page }) => {
  test.setTimeout(120_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/login')
  await page.getByRole('button', { name: 'Continuar como convidado local' }).click()
  await page.getByPlaceholder('Ex.: Aron').fill('TerririanIso')
  await page.getByRole('button', { name: 'Confirmar e continuar' }).click()
  await page.getByRole('button', { name: 'Escolher Espada Longa', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Distribuir pontos e vincular Espada Longa', exact: true }).click()
  for (const attribute of ['Força', 'Força', 'Astúcia', 'Agilidade', 'Vigor', 'Espírito'])
    await page.getByRole('button', { name: 'Aumentar ' + attribute }).click()
  await page.getByRole('button', { name: 'Confirmar Vínculo de Espada Longa — Grau I', exact: true }).click()
  await page.getByRole('button', { name: 'Pular cena' }).click()
  await page.getByRole('link', { name: 'Ativar cena isométrica jogável de Terran' }).click()
  await expect(page).toHaveURL(/\/play\?view=iso/)
  await expect(page.getByRole('region', { name: 'Cenário isométrico jogável de Terran' })).toBeVisible()
  await expect(page.getByRole('complementary', { name: 'Diário de missões' })).toBeVisible()
  await expect(page.getByRole('complementary', { name: 'Status permanente do personagem' })).toBeVisible()
  await expect(page.locator('.iso-play__building')).toHaveCount(9)
  await expect(page.getByRole('button', { name: 'Conversar com Rosetta' })).toBeVisible()
  const before = await page.locator('.iso-play__hero').evaluate((element) => element.style.left)
  await page.keyboard.down('d')
  await page.waitForTimeout(240)
  await page.keyboard.up('d')
  const after = await page.locator('.iso-play__hero').evaluate((element) => element.style.left)
  expect(after).not.toBe(before)
  await page.getByRole('button', { name: 'Entrar em Casa do Ferreiro' }).click()
  await expect(page.getByRole('region', { name: 'Interior isométrico jogável: Casa do Ferreiro' }))
    .toBeVisible({ timeout: 25_000 })
  await expect(page.getByRole('button', { name: 'Interagir com Fornalha de Durnan' })).toBeVisible()
  await page.getByRole('button', { name: 'Sair para Terran' }).click()
  await expect(page.getByRole('region', { name: 'Cenário isométrico jogável de Terran' }))
    .toBeVisible({ timeout: 18_000 })
  await page.getByRole('link', { name: 'Voltar à visão clássica de Terran' }).click()
  await expect(page).toHaveURL(/\/play$/)
  await expect(page.getByRole('region', { name: 'Cenário contínuo de Terran' })).toBeVisible()
  expect(errors).toEqual([])
})
